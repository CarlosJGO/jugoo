def settings_by_key(catalog: tuple[SettingDef, ...] | None = None) -> dict[str, SettingDef]:
    items = catalog if catalog is not None else build_settings_catalog()
    return {item.key: item for item in items}


def settings_for_category(
    category: CategoryId,
    catalog: tuple[SettingDef, ...] | None = None,
) -> tuple[SettingDef, ...]:
    items = catalog if catalog is not None else build_settings_catalog()
    return tuple(item for item in items if item.category is category)


