@dataclass(frozen=True)
class SettingDef:
    key: str
    category: CategoryId
    label: str
    description: str
    value_type: SettingType
    default: Any
    config_attr: str | None = None
    apply: ApplyMode = APPLY_LIVE
    minimum: float | None = None
    maximum: float | None = None
    step: float | None = None
    choices: tuple[tuple[str, str], ...] = ()
    tier: Literal["A", "B", "C"] = "A"
    section: str = ""
    unit: str = ""


def _clock_format_choices() -> tuple[tuple[str, str], ...]:
    return (
        ("%I:%M %p", "12 h (03:45 PM)"),
        ("%H:%M", "24 h (15:45)"),
        ("%I:%M", "12 h sin AM/PM"),
        ("%H:%M:%S", "24 h con segundos"),
    )


def _date_format_choices() -> tuple[tuple[str, str], ...]:
    return (
        ("%a · %d %b", "Lun · 08 sep"),
        ("%A %d %B", "Lunes 08 septiembre"),
        ("%d/%m/%Y", "08/09/2026"),
        ("%Y-%m-%d", "2026-09-08"),
    )


