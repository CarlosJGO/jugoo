SettingType = Literal["bool", "int", "float", "string", "choice", "path"]
ApplyMode = Literal["live", "reload", "restart"]

APPLY_LIVE: ApplyMode = "live"
APPLY_RELOAD: ApplyMode = "reload"
APPLY_RESTART: ApplyMode = "restart"


